<#
.SYNOPSIS
    Builds and installs loomAI on Windows (MSYS2 / MinGW-w64).

.DESCRIPTION
    One-shot setup:
      1. checks the prerequisites (CMake >= 3.20, g++ + mingw32-make, OpenSSL)
      2. vendors the two header-only dependencies into third_party/ (pinned
         versions, SHA-256 verified; existing files are never overwritten)
      3. configures and builds with CMake
      4. installs into <Prefix>\app (binary, dashboard, runtime DLLs) and
         writes the launcher <Prefix>\loomai.cmd
      5. smoke-tests the installed copy against GET /health

    The server mounts ./dashboard relative to its working directory, so it
    must be started from <Prefix>\app -- that is what loomai.cmd does. Put
    <Prefix> (not <Prefix>\app) on PATH, or pass -AddToPath.

    The script never writes API keys anywhere. Set OPENAI_API_KEY,
    ANTHROPIC_API_KEY and GEMINI_API_KEY yourself, see README.md.

.PARAMETER Prefix
    Install root. Default: %LOCALAPPDATA%\loomai.

.PARAMETER BuildType
    CMake build type. Default: Release.

.PARAMETER Msys2Root
    MSYS2 installation. Default: C:\msys64. Ignored if g++ is already on PATH.

.PARAMETER InstallDeps
    Install the missing MSYS2 packages (gcc, make, openssl) via pacman.

.PARAMETER Clean
    Delete the CMake build directory first (needed after switching
    compiler, generator or checkout location).

.PARAMETER CheckOnly
    Only run the prerequisite check, change nothing.

.PARAMETER SkipInstall
    Build only, do not install.

.PARAMETER SkipSmokeTest
    Do not start the installed server for the final /health check.

.PARAMETER AddToPath
    Add <Prefix> to the user PATH (idempotent).

.PARAMETER Uninstall
    Remove <Prefix>\app and <Prefix>\loomai.cmd (and <Prefix> itself if that
    leaves it empty) and drop <Prefix> from the user PATH.

.EXAMPLE
    .\scripts\setup.ps1 -InstallDeps -AddToPath
#>
# Placed after the help block on purpose: a #Requires line in front of it stops Get-Help from finding the block.
#Requires -Version 5.1
[CmdletBinding()]
param(
    [string]$Prefix = (Join-Path $env:LOCALAPPDATA 'loomai'),
    [ValidateSet('Release', 'Debug', 'RelWithDebInfo', 'MinSizeRel')]
    [string]$BuildType = 'Release',
    [string]$Msys2Root = 'C:\msys64',
    [switch]$InstallDeps,
    [switch]$Clean,
    [switch]$CheckOnly,
    [switch]$SkipInstall,
    [switch]$SkipSmokeTest,
    [switch]$AddToPath,
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$RepoRoot = Split-Path -Parent $PSScriptRoot
$BuildDir = Join-Path $RepoRoot 'build'
# Resolve against PowerShell's location, not the .NET process directory.
$Prefix = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Prefix)
$AppDir = Join-Path $Prefix 'app'
$Launcher = Join-Path $Prefix 'loomai.cmd'
$LauncherMarker = 'rem Generated by loomAI scripts/setup.ps1'
$Port = 8080 # hardcoded in src/main.cpp

# Keep in sync with the README's "Building" section. The hashes pin the exact
# upstream release files, so a tampered download is rejected.
$Vendored = @(
    @{
        Path   = 'third_party\nlohmann\json.hpp'
        Url    = 'https://github.com/nlohmann/json/releases/download/v3.11.3/json.hpp'
        Sha256 = '9bea4c8066ef4a1c206b2be5a36302f8926f7fdc6087af5d20b417d0cf103ea6'
    },
    @{
        Path   = 'third_party\httplib.h'
        Url    = 'https://raw.githubusercontent.com/yhirose/cpp-httplib/v0.15.3/httplib.h'
        Sha256 = 'a3347656c71c81c3fe510fdb1ff229d7db52eb7df04d3342d340eba0b6ad50ea'
    }
)
$PacmanPackages = @('mingw-w64-x86_64-gcc', 'mingw-w64-x86_64-make', 'mingw-w64-x86_64-openssl')

function Write-Step([string]$Text) { Write-Host "`n==> $Text" -ForegroundColor Cyan }
function Write-Ok([string]$Text) { Write-Host "  [ OK ] $Text" -ForegroundColor Green }
function Write-Warn([string]$Text) { Write-Host "  [WARN] $Text" -ForegroundColor Yellow }
function Write-Info([string]$Text) { Write-Host "  [INFO] $Text" }

function Invoke-Native([string]$Exe, [string[]]$Arguments) {
    & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "'$Exe $($Arguments -join ' ')' failed with exit code $LASTEXITCODE"
    }
}

function Find-Mingw64Bin {
    $candidates = @()
    $gpp = Get-Command g++ -ErrorAction SilentlyContinue
    if ($gpp) { $candidates += Split-Path -Parent $gpp.Source }
    $candidates += (Join-Path $Msys2Root 'mingw64\bin')
    foreach ($dir in $candidates) {
        if (Test-Path (Join-Path $dir 'g++.exe')) { return $dir }
    }
    return $null
}

function Find-CMake {
    $cmd = Get-Command cmake -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $default = Join-Path $env:ProgramFiles 'CMake\bin\cmake.exe'
    if (Test-Path $default) { return $default }
    return $null
}

function Get-UserPathEntries {
    $raw = [Environment]::GetEnvironmentVariable('Path', 'User')
    if (-not $raw) { return @() }
    return @($raw -split ';' | Where-Object { $_ })
}

function Test-SamePath([string]$A, [string]$B) {
    return $A.TrimEnd('\') -ieq $B.TrimEnd('\')
}

function Test-PortFree([int]$PortNumber) {
    try {
        $listener = New-Object Net.Sockets.TcpListener([Net.IPAddress]::Loopback, $PortNumber)
        $listener.Start()
        $listener.Stop()
        return $true
    } catch {
        return $false
    }
}

function Get-RunningInstall {
    # An installed loomai.exe that is still running keeps its file locked.
    $exe = Join-Path $AppDir 'loomai.exe'
    return @(Get-Process loomai -ErrorAction SilentlyContinue | Where-Object { $_.Path -ieq $exe })
}

# ---------------------------------------------------------------------------
# Uninstall
# ---------------------------------------------------------------------------
if ($Uninstall) {
    Write-Step "Uninstalling loomAI from $Prefix"
    if (-not (Test-Path (Join-Path $AppDir 'loomai.exe'))) {
        throw "No loomAI installation found at $Prefix (expected $AppDir\loomai.exe)."
    }
    if (Get-RunningInstall) {
        throw 'loomai.exe from this installation is still running. Stop it first (Ctrl+C in its console).'
    }
    Remove-Item -LiteralPath $AppDir -Recurse -Force
    Write-Ok "removed $AppDir"
    if ((Test-Path $Launcher) -and ((Get-Content -LiteralPath $Launcher -Raw) -like "*$LauncherMarker*")) {
        Remove-Item -LiteralPath $Launcher -Force
        Write-Ok "removed $Launcher"
    }
    if (-not (Get-ChildItem -LiteralPath $Prefix -Force)) {
        Remove-Item -LiteralPath $Prefix -Force
        Write-Ok "removed empty $Prefix"
    } else {
        Write-Info "$Prefix still holds other files, left in place"
    }
    $entries = Get-UserPathEntries
    $kept = @($entries | Where-Object { -not (Test-SamePath $_ $Prefix) })
    if ($kept.Count -ne $entries.Count) {
        [Environment]::SetEnvironmentVariable('Path', ($kept -join ';'), 'User')
        Write-Ok 'removed from user PATH (restart open terminals)'
    }
    return
}

# ---------------------------------------------------------------------------
# 1. Prerequisites
# ---------------------------------------------------------------------------
Write-Step 'Checking prerequisites'

if ($InstallDeps) {
    $pacman = Join-Path $Msys2Root 'usr\bin\pacman.exe'
    if (-not (Test-Path $pacman)) {
        throw "-InstallDeps needs MSYS2 (pacman not found at $pacman). Install it from https://www.msys2.org or pass -Msys2Root."
    }
    Write-Info "pacman -S --needed $($PacmanPackages -join ' ')"
    Invoke-Native $pacman (@('-S', '--needed', '--noconfirm') + $PacmanPackages)
}

$problems = New-Object System.Collections.Generic.List[string]

$cmake = Find-CMake
if (-not $cmake) {
    $problems.Add('cmake not found (need >= 3.20): winget install -e --id Kitware.CMake')
} else {
    $versionLine = (& $cmake --version | Select-Object -First 1)
    if ($versionLine -match 'version (\d+)\.(\d+)') {
        $cmakeVersion = [version]"$($Matches[1]).$($Matches[2])"
        if ($cmakeVersion -lt [version]'3.20') {
            $problems.Add("cmake $cmakeVersion is too old (need >= 3.20)")
        } else {
            Write-Ok "cmake $cmakeVersion ($cmake)"
        }
    } else {
        Write-Warn "cmake found but its version could not be parsed: $versionLine"
    }
}

$mingwBin = Find-Mingw64Bin
$mingwRoot = $null
if (-not $mingwBin) {
    $problems.Add("g++ not found on PATH or in $Msys2Root\mingw64\bin -- rerun with -InstallDeps (MSYS2 required)")
} else {
    $mingwRoot = Split-Path -Parent $mingwBin
    if (($env:Path -split ';') -notcontains $mingwBin) {
        $env:Path = "$mingwBin;$env:Path" # CMake, the build and the DLL lookup all need it
    }
    $gppVersion = (& (Join-Path $mingwBin 'g++.exe') --version | Select-Object -First 1)
    Write-Ok "g++: $gppVersion"
    if (Test-Path (Join-Path $mingwBin 'mingw32-make.exe')) {
        Write-Ok 'mingw32-make'
    } else {
        $problems.Add("mingw32-make.exe not found in $mingwBin -- pacman -S mingw-w64-x86_64-make")
    }
    if (-not (Test-Path (Join-Path $mingwBin 'objdump.exe'))) {
        $problems.Add("objdump.exe not found in $mingwBin (needed to collect runtime DLLs) -- pacman -S mingw-w64-x86_64-binutils")
    }
    if ((Test-Path (Join-Path $mingwRoot 'include\openssl\ssl.h')) -and (Test-Path (Join-Path $mingwRoot 'lib\libssl.dll.a'))) {
        Write-Ok "OpenSSL headers + libs ($mingwRoot)"
    } else {
        $problems.Add("OpenSSL dev files not found under $mingwRoot -- pacman -S mingw-w64-x86_64-openssl (or rerun with -InstallDeps)")
    }
}

if ($problems.Count -gt 0) {
    $problems | ForEach-Object { Write-Host "  [FAIL] $_" -ForegroundColor Red }
    throw 'Prerequisites missing, see above.'
}

$ollama = $false
try {
    $client = New-Object Net.Sockets.TcpClient
    $ollama = $client.ConnectAsync('127.0.0.1', 11434).Wait(1000)
    $client.Close()
} catch { }
if ($ollama) {
    Write-Ok 'Ollama reachable on 127.0.0.1:11434'
} else {
    Write-Info 'Ollama not reachable on 127.0.0.1:11434 (only needed for the local fallback backend)'
}

if ($CheckOnly) {
    Write-Host "`nPrerequisites OK." -ForegroundColor Green
    return
}

# ---------------------------------------------------------------------------
# 2. Vendored headers
# ---------------------------------------------------------------------------
Write-Step 'Vendoring header-only dependencies into third_party/'
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
foreach ($dep in $Vendored) {
    $target = Join-Path $RepoRoot $dep.Path
    if (Test-Path $target) {
        $actual = (Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($actual -eq $dep.Sha256) {
            Write-Ok "$($dep.Path) (pinned version)"
        } else {
            Write-Warn "$($dep.Path) exists but differs from the pinned release -- leaving it untouched"
        }
        continue
    }
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
    $tmp = "$target.download"
    try {
        Invoke-WebRequest -UseBasicParsing -Uri $dep.Url -OutFile $tmp
        $actual = (Get-FileHash -LiteralPath $tmp -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($actual -ne $dep.Sha256) {
            throw "SHA-256 mismatch for $($dep.Url): expected $($dep.Sha256), got $actual"
        }
        Move-Item -LiteralPath $tmp -Destination $target
        Write-Ok "$($dep.Path) downloaded and verified"
    } finally {
        if (Test-Path $tmp) { Remove-Item -LiteralPath $tmp -Force }
    }
}

# ---------------------------------------------------------------------------
# 3. Configure + build
# ---------------------------------------------------------------------------
Write-Step "Building ($BuildType)"
if ($Clean -and (Test-Path (Join-Path $BuildDir 'CMakeCache.txt'))) {
    Remove-Item -LiteralPath $BuildDir -Recurse -Force
    Write-Ok 'removed old build directory'
}
$configureArgs = @(
    '-S', $RepoRoot, '-B', $BuildDir,
    '-G', 'MinGW Makefiles',
    "-DCMAKE_BUILD_TYPE=$BuildType",
    '-DCMAKE_CXX_COMPILER=g++',
    "-DOPENSSL_ROOT_DIR=$($mingwRoot -replace '\\', '/')"
)
try {
    Invoke-Native $cmake $configureArgs
    Invoke-Native $cmake @('--build', $BuildDir, '-j', $env:NUMBER_OF_PROCESSORS)
} catch {
    Write-Warn 'If the build directory was created with another compiler, generator or checkout location, rerun with -Clean.'
    throw
}
$builtExe = Join-Path $BuildDir 'loomai.exe'
if (-not (Test-Path $builtExe)) { throw "Build finished but $builtExe is missing." }
Write-Ok $builtExe

if ($SkipInstall) {
    Write-Host "`nBuild finished (install skipped). Run it from the repo root: .\build\loomai.exe" -ForegroundColor Green
    return
}

# ---------------------------------------------------------------------------
# 4. Install
# ---------------------------------------------------------------------------
Write-Step "Installing to $Prefix"
if (Get-RunningInstall) {
    throw 'loomai.exe from this installation is running and locks its files. Stop it, then rerun.'
}
Invoke-Native $cmake @('--install', $BuildDir, '--prefix', $AppDir)

# The MinGW build links libstdc++/libssl/... dynamically. Copy every DLL the
# binary needs from the MinGW bin directory (transitively), so the installed
# copy runs without MSYS2 on PATH. System DLLs are not in that directory and
# are skipped on their own.
$objdump = Join-Path $mingwBin 'objdump.exe'
$queue = New-Object System.Collections.Generic.Queue[string]
$seen = @{}
$queue.Enqueue((Join-Path $AppDir 'loomai.exe'))
while ($queue.Count -gt 0) {
    $binary = $queue.Dequeue()
    foreach ($line in (& $objdump -p $binary)) {
        if ($line -match 'DLL Name:\s*(\S+)') {
            $name = $Matches[1]
            $source = Join-Path $mingwBin $name
            if (-not $seen.ContainsKey($name.ToLowerInvariant()) -and (Test-Path $source)) {
                $seen[$name.ToLowerInvariant()] = $true
                Copy-Item -LiteralPath $source -Destination $AppDir -Force
                $queue.Enqueue((Join-Path $AppDir $name))
            }
        }
    }
}
Write-Ok "installed $(@($seen.Keys).Count) runtime DLL(s) next to loomai.exe"

$launcherText = @(
    '@echo off',
    $LauncherMarker,
    'rem The server serves .\dashboard relative to its working directory.',
    'pushd "%~dp0app" || exit /b 1',
    'rem Explicit path: cmd skips the current directory when NoDefaultCurrentDirectoryInExePath is set.',
    '"%~dp0app\loomai.exe" %*',
    'set "LOOMAI_RC=%errorlevel%"',
    'popd',
    'exit /b %LOOMAI_RC%'
) -join "`r`n"
Set-Content -LiteralPath $Launcher -Value $launcherText -Encoding ASCII
Write-Ok "launcher $Launcher"

if ($AddToPath) {
    $entries = Get-UserPathEntries
    if (@($entries | Where-Object { Test-SamePath $_ $Prefix }).Count -eq 0) {
        [Environment]::SetEnvironmentVariable('Path', (($entries + $Prefix) -join ';'), 'User')
        Write-Ok "added $Prefix to the user PATH (restart open terminals)"
    } else {
        Write-Ok 'already on the user PATH'
    }
}

# ---------------------------------------------------------------------------
# 5. Smoke test of the installed copy
# ---------------------------------------------------------------------------
if (-not $SkipSmokeTest) {
    Write-Step 'Smoke test (installed copy, GET /health)'
    if (-not (Test-PortFree $Port)) {
        Write-Warn "port $Port is in use (loomAI already running?) -- skipping the smoke test"
    } else {
        $logOut = Join-Path ([IO.Path]::GetTempPath()) 'loomai-setup.out.log'
        $logErr = Join-Path ([IO.Path]::GetTempPath()) 'loomai-setup.err.log'
        # Run with a minimal PATH (no MinGW) to prove the installed copy is
        # self-contained, then restore it.
        $savedPath = $env:Path
        $env:Path = "$env:SystemRoot\System32;$env:SystemRoot"
        $proc = $null
        try {
            $proc = Start-Process -FilePath (Join-Path $AppDir 'loomai.exe') -WorkingDirectory $AppDir `
                -WindowStyle Hidden -PassThru -RedirectStandardOutput $logOut -RedirectStandardError $logErr
        } finally {
            $env:Path = $savedPath
        }
        try {
            $health = $null
            for ($i = 0; $i -lt 15 -and -not $health; $i++) {
                Start-Sleep -Seconds 1
                if ($proc.HasExited) { break }
                try { $health = Invoke-RestMethod -Uri "http://127.0.0.1:$Port/health" -TimeoutSec 2 } catch { }
            }
            if ($health -and $health.status -eq 'ready') {
                Write-Ok "/health: status=$($health.status)"
                $backends = ($health.backends.PSObject.Properties | ForEach-Object { "$($_.Name)=$($_.Value)" }) -join ', '
                Write-Info "backends: $backends"
            } else {
                $detail = ''
                if (Test-Path $logErr) { $detail = (Get-Content -LiteralPath $logErr -Raw) }
                throw "Installed server did not answer /health. $(if ($proc.HasExited) { "It exited with code $($proc.ExitCode). " })$detail"
            }
        } finally {
            if ($proc -and -not $proc.HasExited) { Stop-Process -Id $proc.Id -Force }
            Remove-Item -LiteralPath $logOut, $logErr -Force -ErrorAction SilentlyContinue
        }
    }
}

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
Write-Host @"

loomAI is installed.

  Start:      $Launcher         (binds 127.0.0.1:$Port, Ctrl+C stops it)
  Dashboard:  http://127.0.0.1:$Port/
  Uninstall:  .\scripts\setup.ps1 -Uninstall$(if ($Prefix -ne (Join-Path $env:LOCALAPPDATA 'loomai')) { " -Prefix `"$Prefix`"" })

Cloud backends read their keys from the environment (set them yourself, the
installer never stores secrets):
  OPENAI_API_KEY   ANTHROPIC_API_KEY   GEMINI_API_KEY
Local fallback: Ollama on 127.0.0.1:11434 (LOOMAI_OLLAMA_HOST, LOOMAI_DEFAULT_MODEL).

ai.nvim: the "loomai" provider talks to http://127.0.0.1:$Port by default
(override with LOOMAI_HOST).
"@ -ForegroundColor Green
