#!/usr/bin/env bash
# Builds and installs loomAI on Linux and macOS (on Windows use setup.ps1).
#
#   1. checks the prerequisites (CMake >= 3.20, a C++17 compiler, curl)
#   2. vendors the two header-only dependencies into third_party/ (pinned
#      versions, SHA-256 verified; existing files are never overwritten)
#   3. configures and builds with CMake (OpenSSL is located by CMake itself)
#   4. installs into <prefix>/app and writes the launcher <bin-dir>/loomai
#   5. smoke-tests the installed copy against GET /health
#
# The server mounts ./dashboard relative to its working directory, so it must
# be started from <prefix>/app -- that is what the launcher does.
#
# The script never writes API keys anywhere. Set OPENAI_API_KEY,
# ANTHROPIC_API_KEY and GEMINI_API_KEY yourself, see README.md.

set -euo pipefail

usage() {
    cat <<'EOF'
Usage: scripts/setup.sh [options]

  --prefix DIR        install root (default: ~/.local/share/loomai, env LOOMAI_PREFIX)
  --bin-dir DIR       where the launcher "loomai" goes (default: ~/.local/bin, env LOOMAI_BIN_DIR)
  --build-type TYPE   Release | Debug | RelWithDebInfo | MinSizeRel (default: Release)
  --check             only check the prerequisites, change nothing
  --clean             delete the CMake build directory first
  --skip-install      build only, do not install
  --skip-smoke-test   do not start the installed server for the final /health check
  --uninstall         remove <prefix>/app and the launcher
  -h, --help          show this help
EOF
}

PREFIX="${LOOMAI_PREFIX:-$HOME/.local/share/loomai}"
BIN_DIR="${LOOMAI_BIN_DIR:-$HOME/.local/bin}"
BUILD_TYPE=Release
CHECK_ONLY=0
CLEAN=0
SKIP_INSTALL=0
SKIP_SMOKE=0
UNINSTALL=0

while [ $# -gt 0 ]; do
    case "$1" in
        --prefix)      PREFIX="${2:?--prefix needs a value}"; shift 2 ;;
        --bin-dir)     BIN_DIR="${2:?--bin-dir needs a value}"; shift 2 ;;
        --build-type)  BUILD_TYPE="${2:?--build-type needs a value}"; shift 2 ;;
        --check)       CHECK_ONLY=1; shift ;;
        --clean)       CLEAN=1; shift ;;
        --skip-install) SKIP_INSTALL=1; shift ;;
        --skip-smoke-test) SKIP_SMOKE=1; shift ;;
        --uninstall)   UNINSTALL=1; shift ;;
        -h|--help)     usage; exit 0 ;;
        *)             echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
done

case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*)
        echo "On Windows use scripts/setup.ps1 (MSYS2/MinGW-w64 toolchain)." >&2
        exit 1 ;;
esac

# The launcher bakes the install path in, so a relative --prefix/--bin-dir would
# break as soon as it is run from another directory.
case "$PREFIX" in /*) ;; *) PREFIX="$PWD/$PREFIX" ;; esac
case "$BIN_DIR" in /*) ;; *) BIN_DIR="$PWD/$BIN_DIR" ;; esac

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD_DIR="$REPO_ROOT/build"
APP_DIR="$PREFIX/app"
LAUNCHER="$BIN_DIR/loomai"
LAUNCHER_MARKER="# Generated by loomAI scripts/setup.sh"
PORT=8080 # hardcoded in src/main.cpp

# Keep in sync with the README's "Building" section. The hashes pin the exact
# upstream release files, so a tampered download is rejected.
JSON_URL="https://github.com/nlohmann/json/releases/download/v3.11.3/json.hpp"
JSON_SHA256="9bea4c8066ef4a1c206b2be5a36302f8926f7fdc6087af5d20b417d0cf103ea6"
HTTPLIB_URL="https://raw.githubusercontent.com/yhirose/cpp-httplib/v0.15.3/httplib.h"
HTTPLIB_SHA256="a3347656c71c81c3fe510fdb1ff229d7db52eb7df04d3342d340eba0b6ad50ea"

step() { printf '\n==> %s\n' "$*"; }
ok()   { printf '  [ OK ] %s\n' "$*"; }
warn() { printf '  [WARN] %s\n' "$*"; }
info() { printf '  [INFO] %s\n' "$*"; }
fail() { printf '  [FAIL] %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

# Prints the PID(s) of a loomai process whose executable is the installed one.
# The path goes into an extended regex, so escape its metacharacters first.
running_install() {
    command -v pgrep >/dev/null 2>&1 || return 0
    local escaped
    escaped="$(printf '%s' "$APP_DIR/loomai" | sed 's/[][\.*^$+?(){}|]/\\&/g')"
    pgrep -f "^$escaped( |\$)" 2>/dev/null || true
}

# True if something already listens on 127.0.0.1:<port>. A plain TCP connect
# (bash's /dev/tcp) rather than an HTTP request: another service that answers
# 404 or speaks another protocol must count as "in use" too.
port_in_use() {
    (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
}

# ---------------------------------------------------------------------------
# Uninstall
# ---------------------------------------------------------------------------
if [ "$UNINSTALL" -eq 1 ]; then
    step "Uninstalling loomAI from $PREFIX"
    [ -x "$APP_DIR/loomai" ] || die "no loomAI installation found at $PREFIX (expected $APP_DIR/loomai)"
    [ -z "$(running_install)" ] || die "loomai from this installation is still running; stop it first (Ctrl+C)"
    rm -rf -- "$APP_DIR"
    ok "removed $APP_DIR"
    if [ -f "$LAUNCHER" ] && grep -qF "$LAUNCHER_MARKER" "$LAUNCHER"; then
        rm -f -- "$LAUNCHER"
        ok "removed $LAUNCHER"
    fi
    rmdir "$PREFIX" 2>/dev/null && ok "removed empty $PREFIX" || info "$PREFIX still holds other files, left in place"
    exit 0
fi

# ---------------------------------------------------------------------------
# 1. Prerequisites
# ---------------------------------------------------------------------------
step "Checking prerequisites"
problems=0

if command -v cmake >/dev/null 2>&1; then
    cmake_version="$(cmake --version | head -n1 | sed -n 's/.*version \([0-9]*\.[0-9]*\).*/\1/p')"
    cmake_major="${cmake_version%%.*}"
    cmake_minor="${cmake_version##*.}"
    if [ -n "$cmake_version" ] && { [ "$cmake_major" -gt 3 ] || { [ "$cmake_major" -eq 3 ] && [ "$cmake_minor" -ge 20 ]; }; }; then
        ok "cmake $cmake_version"
    else
        fail "cmake ${cmake_version:-?} is too old (need >= 3.20)"; problems=1
    fi
else
    fail "cmake not found (need >= 3.20)"; problems=1
fi

CXX_BIN="${CXX:-}"
if [ -z "$CXX_BIN" ]; then
    for candidate in c++ g++ clang++; do
        if command -v "$candidate" >/dev/null 2>&1; then CXX_BIN="$candidate"; break; fi
    done
fi
if [ -n "$CXX_BIN" ] && command -v "$CXX_BIN" >/dev/null 2>&1; then
    ok "C++ compiler: $("$CXX_BIN" --version | head -n1)"
else
    fail "no C++ compiler found (g++ or clang++, C++17)"; problems=1
fi

if command -v curl >/dev/null 2>&1; then ok "curl"; else fail "curl not found"; problems=1; fi

if [ "$problems" -ne 0 ]; then
    cat >&2 <<'EOF'

Install the missing tools, e.g.
  Debian/Ubuntu:  sudo apt install build-essential cmake curl libssl-dev
  Fedora:         sudo dnf install gcc-c++ cmake curl openssl-devel
  Arch:           sudo pacman -S base-devel cmake curl openssl
  macOS:          xcode-select --install && brew install cmake openssl@3
EOF
    exit 1
fi

if curl -fs --max-time 1 "http://127.0.0.1:11434/api/tags" >/dev/null 2>&1; then
    ok "Ollama reachable on 127.0.0.1:11434"
else
    info "Ollama not reachable on 127.0.0.1:11434 (only needed for the local fallback backend)"
fi

if [ "$CHECK_ONLY" -eq 1 ]; then
    echo
    echo "Prerequisites OK (OpenSSL dev files are located by CMake during the build)."
    exit 0
fi

# ---------------------------------------------------------------------------
# 2. Vendored headers
# ---------------------------------------------------------------------------
step "Vendoring header-only dependencies into third_party/"
vendor() { # <relative path> <url> <sha256>
    local rel="$1" url="$2" want="$3" target="$REPO_ROOT/$1" tmp
    if [ -f "$target" ]; then
        if [ "$(sha256_of "$target")" = "$want" ]; then
            ok "$rel (pinned version)"
        else
            warn "$rel exists but differs from the pinned release -- leaving it untouched"
        fi
        return 0
    fi
    mkdir -p "$(dirname "$target")"
    tmp="$target.download"
    if ! curl -fsSL "$url" -o "$tmp"; then
        rm -f -- "$tmp"
        die "download failed: $url"
    fi
    if [ "$(sha256_of "$tmp")" != "$want" ]; then
        rm -f -- "$tmp"
        die "SHA-256 mismatch for $url"
    fi
    mv -- "$tmp" "$target"
    ok "$rel downloaded and verified"
}
vendor "third_party/nlohmann/json.hpp" "$JSON_URL" "$JSON_SHA256"
vendor "third_party/httplib.h" "$HTTPLIB_URL" "$HTTPLIB_SHA256"

# ---------------------------------------------------------------------------
# 3. Configure + build
# ---------------------------------------------------------------------------
step "Building ($BUILD_TYPE)"
if [ "$CLEAN" -eq 1 ] && [ -f "$BUILD_DIR/CMakeCache.txt" ]; then
    rm -rf -- "$BUILD_DIR"
    ok "removed old build directory"
fi

configure_args=(-S "$REPO_ROOT" -B "$BUILD_DIR" "-DCMAKE_BUILD_TYPE=$BUILD_TYPE" "-DCMAKE_CXX_COMPILER=$CXX_BIN")
# Homebrew's OpenSSL is keg-only, CMake does not find it on its own.
if [ -z "${OPENSSL_ROOT_DIR:-}" ] && [ "$(uname -s)" = "Darwin" ] && command -v brew >/dev/null 2>&1; then
    if brew_openssl="$(brew --prefix openssl@3 2>/dev/null)"; then
        configure_args+=("-DOPENSSL_ROOT_DIR=$brew_openssl")
    fi
fi

if ! cmake "${configure_args[@]}"; then
    warn "Configure failed. Missing OpenSSL dev files? (apt: libssl-dev, dnf: openssl-devel, brew: openssl@3)"
    warn "If the build directory was created with another compiler or checkout location, rerun with --clean."
    exit 1
fi
cmake --build "$BUILD_DIR" -j "$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 2)"
[ -x "$BUILD_DIR/loomai" ] || die "build finished but $BUILD_DIR/loomai is missing"
ok "$BUILD_DIR/loomai"

if [ "$SKIP_INSTALL" -eq 1 ]; then
    echo
    echo "Build finished (install skipped). Run it from the repo root: ./build/loomai"
    exit 0
fi

# ---------------------------------------------------------------------------
# 4. Install
# ---------------------------------------------------------------------------
step "Installing to $PREFIX"
[ -z "$(running_install)" ] || die "loomai from this installation is running; stop it, then rerun"
cmake --install "$BUILD_DIR" --prefix "$APP_DIR"

mkdir -p "$BIN_DIR"
{
    echo '#!/bin/sh'
    echo "$LAUNCHER_MARKER"
    echo '# The server serves ./dashboard relative to its working directory.'
    printf 'cd %q || exit 1\n' "$APP_DIR"
    # Absolute path, so running_install() can recognise the process by its command line.
    printf 'exec %q "$@"\n' "$APP_DIR/loomai"
} > "$LAUNCHER"
chmod +x "$LAUNCHER"
ok "launcher $LAUNCHER"

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) warn "$BIN_DIR is not on your PATH -- add it, e.g.: export PATH=\"$BIN_DIR:\$PATH\"" ;;
esac

# ---------------------------------------------------------------------------
# 5. Smoke test of the installed copy
# ---------------------------------------------------------------------------
if [ "$SKIP_SMOKE" -eq 0 ]; then
    step "Smoke test (installed copy, GET /health)"
    if port_in_use "$PORT"; then
        warn "port $PORT is in use (loomAI already running?) -- skipping the smoke test"
    else
        log="$(mktemp "${TMPDIR:-/tmp}/loomai-setup.XXXXXX")"
        ( cd "$APP_DIR" && exec "$APP_DIR/loomai" ) >"$log" 2>&1 &
        server_pid=$!
        trap 'kill "$server_pid" 2>/dev/null || true; rm -f -- "$log"' EXIT
        health=""
        for _ in $(seq 1 15); do
            sleep 1
            kill -0 "$server_pid" 2>/dev/null || break
            health="$(curl -fs --max-time 2 "http://127.0.0.1:$PORT/health" 2>/dev/null || true)"
            [ -n "$health" ] && break
        done
        case "$health" in
            *'"status":"ready"'*|*'"status": "ready"'*) ok "/health: $health" ;;
            *) cat "$log" >&2; die "installed server did not answer /health" ;;
        esac
    fi
fi

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
cat <<EOF

loomAI is installed.

  Start:      $LAUNCHER        (binds 127.0.0.1:$PORT, Ctrl+C stops it)
  Dashboard:  http://127.0.0.1:$PORT/
  Uninstall:  scripts/setup.sh --uninstall

Cloud backends read their keys from the environment (set them yourself, the
installer never stores secrets):
  OPENAI_API_KEY   ANTHROPIC_API_KEY   GEMINI_API_KEY
Local fallback: Ollama on 127.0.0.1:11434 (LOOMAI_OLLAMA_HOST, LOOMAI_DEFAULT_MODEL).

ai.nvim: the "loomai" provider talks to http://127.0.0.1:$PORT by default
(override with LOOMAI_HOST).
EOF
